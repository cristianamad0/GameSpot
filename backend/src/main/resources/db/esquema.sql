-- 6. Notificaciones automáticas (confirmación y recordatorio)
-- ---------------------------------------------------------------------

create table public.notificaciones (
  id               bigint generated by default as identity primary key,
  usuario_id       bigint not null references public.usuarios (id),
  reserva_id       bigint references public.reservas (id),
  tipo             text not null check (tipo in ('CONFIRMACION', 'RECORDATORIO')),
  canal            text not null default 'CORREO' check (canal in ('CORREO', 'PUSH')),
  programada_para  timestamptz not null default now(),
  fue_enviada      boolean not null default false,
  enviada_en       timestamptz,
  intentos         integer not null default 0 check (intentos >= 0),
  ultimo_error     text,
  creado_en        timestamptz not null default now(),
  constraint notificaciones_enviada_tiene_fecha
    check (not fue_enviada or enviada_en is not null)
);

create index notificaciones_por_enviar_idx on public.notificaciones (programada_para)
  where not fue_enviada;


-- ---------------------------------------------------------------------
