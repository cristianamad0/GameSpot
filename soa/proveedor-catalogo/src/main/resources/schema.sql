-- CACS-25: DDL del proveedor de catálogo (H2). Crea las tablas solo si no
-- existen, así los datos se conservan al reiniciar.

create table if not exists modalidades (
  id                       bigint generated by default as identity primary key,
  nombre                   varchar(60) not null unique,
  tarifa_hora_pesos        integer not null check (tarifa_hora_pesos between 1 and 1000000),
  -- CACS-30: la media hora tiene su propio precio (no es la mitad de la hora).
  -- Admite null igual que en las bases anteriores (ver el alter de abajo):
  -- data.sql la llena y la API la exige en PUT /api/modalidades/{id}.
  tarifa_media_hora_pesos  integer check (tarifa_media_hora_pesos between 1 and 1000000),
  esta_activa              boolean not null default true
);

-- CACS-30: las bases creadas antes de este cambio no tienen la columna; se
-- agrega vacía y data.sql la llena una sola vez con los precios del propietario.
alter table modalidades add column if not exists tarifa_media_hora_pesos integer
  check (tarifa_media_hora_pesos between 1 and 1000000);

create table if not exists equipos (
  id               bigint generated by default as identity primary key,
  nombre           varchar(60) not null unique,
  modalidad_id     bigint not null references modalidades (id),
  esta_disponible  boolean not null default true
);

create table if not exists horarios_atencion (
  dia_semana     smallint primary key check (dia_semana between 1 and 7),
  hora_apertura  time not null,
  hora_cierre    time not null,
  check (hora_cierre > hora_apertura)
);
