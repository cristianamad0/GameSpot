-- CACS-26: DDL del proveedor de reservas (H2). Crea las tablas solo si no
-- existen, así los datos se conservan al reiniciar.

create table if not exists usuarios (
  id             bigint generated by default as identity primary key,
  nombre         varchar(80) not null,
  email          varchar(160) not null unique,
  password_hash  varchar(100) not null,
  rol            varchar(20) not null check (rol in ('CLIENTE', 'ADMIN'))
);

-- equipo_id apunta a un equipo del proveedor de catálogo, que es otra
-- aplicación con su propia base: por eso no hay clave foránea hacia equipos.
create table if not exists reservas (
  id                  bigint generated by default as identity primary key,
  usuario_id          bigint not null references usuarios (id),
  equipo_id           bigint not null,
  nombre_equipo       varchar(60) not null,
  inicio              timestamp with time zone not null,
  fin                 timestamp with time zone not null,
  precio_total_pesos  integer not null check (precio_total_pesos > 0),
  adelanto_pesos      integer not null check (adelanto_pesos > 0),
  estado              varchar(20) not null
                      check (estado in ('PENDIENTE_PAGO', 'CONFIRMADA', 'CANCELADA')),
  creada_en           timestamp with time zone not null,
  cancelada_en        timestamp with time zone,
  check (fin > inicio),
  check (adelanto_pesos <= precio_total_pesos)
);

create index if not exists reservas_equipo_inicio_idx on reservas (equipo_id, inicio);
